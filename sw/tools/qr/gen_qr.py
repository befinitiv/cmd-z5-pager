# QR code bitmap for the About screen (src/screens/about.c). The URL is fixed,
# so the bitmap is generated once and committed. Needs the qrcode module
# (pip install qrcode). Run from sw/:
#   python3 tools/qr/gen_qr.py > src/screens/qr_project.h
import qrcode

URL = 'https://github.com/befinitiv/cmd-z5-pager'

qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=0)
qr.add_data(URL)
qr.make(fit=True)
m = qr.get_matrix()
n = len(m)
stride = (n + 7) // 8

print('/* Generated by tools/qr/gen_qr.py, do not edit. */')
print('/* QR code (version %d, error correction M) of %s */' % (qr.version, URL))
print()
print('#pragma once')
print()
print('#include <stdint.h>')
print()
print('#define QR_PROJECT_SIZE %d' % n)
print('#define QR_PROJECT_URL "%s"' % URL)
print()
print('/* Rows of modules, MSB = leftmost, 1 = dark. */')
print('static const uint8_t qr_project[QR_PROJECT_SIZE][%d] = {' % stride)
for row in m:
    bits = 0
    for i, dark in enumerate(row):
        if dark:
            bits |= 1 << (stride * 8 - 1 - i)
    data = bits.to_bytes(stride, 'big')
    print('\t{' + ', '.join('0x%02x' % b for b in data) + '},')
print('};')
