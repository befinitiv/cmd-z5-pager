/*
 * Renders the bootloader's screen with the device's own graphics and fonts
 * (lib/gfx) and prints it as a C header. MCUboot has no font or graphics
 * code; it only copies these rows to the display. Run from sw/:
 *   tools/bootscreen/gen_bootscreen.sh > boot/src/bootscreen.h
 */

#include <stdio.h>

#include "gfx/gfx.h"

static struct gfx g;

int main(void)
{
	gfx_init(&g);
	gfx_clear(&g, GFX_WHITE);

	/* Title bar as on the device's screens (ui_draw_title()). */
	gfx_fill_rect(&g, 0, 0, GFX_WIDTH, 9, GFX_DARK);
	gfx_text_aligned(&g, gfx_font_text, 2, 1, GFX_WIDTH - 4, GFX_ALIGN_CENTER, "Bootloader",
			 GFX_WHITE);

	gfx_text_aligned(&g, gfx_font_text, 0, 14, GFX_WIDTH, GFX_ALIGN_CENTER, "USB-Update",
			 GFX_BLACK);
	gfx_text_aligned(&g, gfx_font_small, 0, 24, GFX_WIDTH, GFX_ALIGN_CENTER,
			 "USB update mode", GFX_DARK);

	gfx_hline(&g, 8, 35, GFX_WIDTH - 16, GFX_LIGHT);

	gfx_text_aligned(&g, gfx_font_small, 0, 41, GFX_WIDTH, GFX_ALIGN_CENTER,
			 "Ohne PC startet", GFX_BLACK);
	gfx_text_aligned(&g, gfx_font_small, 0, 48, GFX_WIDTH, GFX_ALIGN_CENTER,
			 "die App von selbst", GFX_BLACK);
	gfx_text_aligned(&g, gfx_font_small, 0, 58, GFX_WIDTH, GFX_ALIGN_CENTER,
			 "No PC: the app starts", GFX_DARK);

	printf("/* Generated by tools/bootscreen/gen_bootscreen.sh, do not edit. */\n\n");
	printf("#pragma once\n\n#include <stdint.h>\n\n");
	printf("/* %d rows of %d bytes as the display takes them (2 bpp, 0 = white). */\n",
	       GFX_HEIGHT, GFX_STRIDE);
	printf("static const uint8_t bootscreen[%d][%d] = {\n", GFX_HEIGHT, GFX_STRIDE);
	for (int y = 0; y < GFX_HEIGHT; y++) {
		printf("\t{");
		for (int x = 0; x < GFX_STRIDE; x++) {
			printf("0x%02x%s", g.fb[y * GFX_STRIDE + x], x + 1 < GFX_STRIDE ? ", " : "");
		}
		printf("},\n");
	}
	printf("};\n");
	return 0;
}
