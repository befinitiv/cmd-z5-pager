#!/usr/bin/env python3
"""Generate crypto test vectors for lib/meshtastic with an independent
implementation (Python 'cryptography'), following the Meshtastic nonce
layouts. Writes vectors.h next to this script."""

import hashlib
import os
import random
import struct

from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESCCM
from cryptography.hazmat.primitives import serialization

rnd = random.Random(42)
DEFAULT_PSK = bytes([0xd4, 0xf1, 0xbb, 0x3a, 0x20, 0x29, 0x07, 0x59,
                     0xf0, 0xbc, 0xff, 0xab, 0xcf, 0x4e, 0x69, 0x01])


def c_bytes(name, b):
    body = ", ".join(f"0x{x:02x}" for x in b)
    return f"static const uint8_t {name}[{len(b)}] = {{{body}}};\n"


def raw(pub):
    return pub.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


out = ["/* Generated by gen_vectors.py with Python cryptography. Do not edit. */\n",
       "#pragma once\n#include <stdint.h>\n\n"]

# Channel encryption: AES-128-CTR, nonce = id (u64 LE) | from (u32 LE) | 0.
frm, pid = 0x12345678, 0xdeadbeef
plain = bytes(rnd.randrange(256) for _ in range(50))
nonce = struct.pack("<QI", pid, frm) + bytes(4)
enc = Cipher(algorithms.AES(DEFAULT_PSK), modes.CTR(nonce)).encryptor()
out.append(f"#define CH_FROM 0x{frm:08x}u\n#define CH_ID 0x{pid:08x}u\n")
out.append(c_bytes("ch_plain", plain))
out.append(c_bytes("ch_cipher", enc.update(plain) + enc.finalize()))

# AES-256-CTR with a 2-byte-index PSK expansion is the same code path; test key length 32.
key32 = bytes(rnd.randrange(256) for _ in range(32))
enc = Cipher(algorithms.AES(key32), modes.CTR(nonce)).encryptor()
out.append(c_bytes("ch256_key", key32))
out.append(c_bytes("ch256_cipher", enc.update(plain) + enc.finalize()))

# X25519 between two random key pairs, and the PKI encryption of a message.
a_priv = bytes(rnd.randrange(256) for _ in range(32))
b_priv = bytes(rnd.randrange(256) for _ in range(32))
a = X25519PrivateKey.from_private_bytes(a_priv)
b = X25519PrivateKey.from_private_bytes(b_priv)
secret = a.exchange(b.public_key())
out.append(c_bytes("a_priv", a_priv))
out.append(c_bytes("a_pub", raw(a.public_key())))
out.append(c_bytes("b_priv", b_priv))
out.append(c_bytes("b_pub", raw(b.public_key())))
out.append(c_bytes("ab_secret", secret))
shared = hashlib.sha256(secret).digest()
out.append(c_bytes("ab_shared", shared))

extra = 0x0badcafe
pki_plain = b"\x08\x01\x12\x0bHallo Welt!"
pki_nonce = struct.pack("<III", pid, extra, frm) + b"\x00"
ct = AESCCM(shared, tag_length=8).encrypt(pki_nonce, pki_plain, None)
out.append(f"#define PKI_EXTRA 0x{extra:08x}u\n")
out.append(c_bytes("pki_plain", pki_plain))
out.append(c_bytes("pki_cipher", ct + struct.pack("<I", extra)))

# SHA-256 of 1000 bytes (several blocks).
data = bytes(rnd.randrange(256) for _ in range(1000))
out.append(c_bytes("sha_data", data))
out.append(c_bytes("sha_digest", hashlib.sha256(data).digest()))

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "vectors.h"), "w") as f:
    f.write("".join(out))
