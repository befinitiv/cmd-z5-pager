#!/usr/bin/env python3
"""Test vectors for lib/meshcore, from Python's cryptography package.

Writes vectors.h. Run from this directory: python3 gen_vectors.py
"""
import hashlib, hmac
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey, X25519PublicKey
from cryptography.hazmat.primitives import serialization

P = 2**255 - 19
raw = serialization.Encoding.Raw, serialization.PublicFormat.Raw


def ed_pub(seed):
    return Ed25519PrivateKey.from_private_bytes(seed).public_key().public_bytes(*raw)


def shared(seed, their_pub):
    """MeshCore: X25519 with the clamped SHA-512 of the seed and the peer's key as Montgomery u."""
    scalar = hashlib.sha512(seed).digest()[:32]
    y = int.from_bytes(their_pub, "little") & ((1 << 255) - 1)
    u = (1 + y) * pow(1 - y, P - 2, P) % P
    return X25519PrivateKey.from_private_bytes(scalar).exchange(
        X25519PublicKey.from_public_bytes(u.to_bytes(32, "little")))


def c(name, b):
    return "static const char %s[] = \"%s\";\n" % (name, b.hex())


seed_a = bytes(range(32))
seed_b = bytes(range(100, 132))
pub_a, pub_b = ed_pub(seed_a), ed_pub(seed_b)
msg = b"MeshCore advert test message"
sig_a = Ed25519PrivateKey.from_private_bytes(seed_a).sign(msg)

public = bytes.fromhex("8b3387e9c5cdea6ac9e5edbaa115cd72")
scope = hashlib.sha256(b"#de-sh").digest()[:16]
# A GRP_TXT packet's payload: transport code over the type byte and payload.
payload = bytes(range(40))
code = hmac.new(scope, bytes([5]) + payload, hashlib.sha256).digest()[:2]

out = "/* Generated by gen_vectors.py. */\n\n"
out += c("SEED_A", seed_a) + c("PUB_A", pub_a) + c("SEED_B", seed_b) + c("PUB_B", pub_b)
out += c("MSG", msg) + c("SIG_A", sig_a)
out += c("SECRET_AB", shared(seed_a, pub_b))
out += "#define PUBLIC_HASH 0x%02x\n" % hashlib.sha256(public).digest()[0]
out += c("SCOPE_DE_SH", scope)
out += "#define CODE_DE_SH 0x%04x\n" % int.from_bytes(code, "little")
out += c("PING_SECRET", hashlib.sha256(b"#ping").digest()[:16])
open("vectors.h", "w").write(out)
